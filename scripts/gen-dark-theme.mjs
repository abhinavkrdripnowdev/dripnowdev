// Generates src/styles/dark-dashboards.css: dark-mode overrides for the dashboard
// stylesheets, derived from their light-mode colours. Re-run after editing those files:
//   node scripts/gen-dark-theme.mjs
import postcss from 'postcss';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = [
  'src/components/layout/DashboardLayout/DashboardLayout.css',
  'src/features/seller/dashboard/SellerWorkspace.css',
  'src/features/delivery/dashboard/DeliveryWorkspace.css',
  'src/features/admin/dashboard/AdminWorkspace.css',
];

// ── colour helpers ────────────────────────────────────────────────────────────
const expand = (h) => (h.length === 4 || h.length === 5 ? '#' + [...h.slice(1)].map((c) => c + c).join('') : h);
function hexToHsl(hex) {
  const h = expand(hex).slice(1);
  const r = parseInt(h.slice(0, 2), 16) / 255, g = parseInt(h.slice(2, 4), 16) / 255, b = parseInt(h.slice(4, 6), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  let hue = 0, s = 0;
  if (d) {
    s = d / (1 - Math.abs(2 * l - 1));
    hue = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    hue = (hue * 60 + 360) % 360;
  }
  return { h: hue, s, l, a: h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1 };
}
function hslToHex({ h, s, l, a }) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = l - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  const to = (v) => Math.round((v + m) * 255).toString(16).padStart(2, '0');
  return `#${to(r)}${to(g)}${to(b)}${a < 1 ? Math.round(a * 255).toString(16).padStart(2, '0') : ''}`;
}
const clamp = (v) => Math.max(0, Math.min(1, v));

const RULES = {
  bg: (c) => (c.l > 0.8 ? { ...c, l: 0.085 + (1 - c.l) * 0.9, s: c.s * 0.55 } : null),
  text: (c) => (c.l < 0.5 ? { ...c, l: clamp(0.93 - c.l * 0.7), s: c.s * 0.8 } : null),
  border: (c) => (c.l > 0.7 ? { ...c, l: 0.2 + (1 - c.l) * 0.45, s: c.s * 0.5 } : null),
};

function kindOf(prop, value) {
  const p = prop.toLowerCase();
  if (p.startsWith('--')) {
    if (/ink|text|fg|color-text/.test(p)) return 'text';
    if (/line|border|stroke/.test(p)) return 'border';
    if (/soft|bg|surface|paper|panel|card|canvas|tint/.test(p)) return 'bg';
    return null; // brand / status colours stay as authored
  }
  if (p === 'color') return 'text';
  if (p.startsWith('background')) return 'bg';
  if (p.startsWith('border') || p.startsWith('outline')) return /color|border|outline/.test(p) ? 'border' : null;
  return null;
}

function transform(prop, value) {
  const kind = kindOf(prop, value);
  if (!kind) return null;
  let changed = false;
  let out = value.replace(/#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b/g, (m) => {
    const next = RULES[kind](hexToHsl(m));
    if (!next) return m;
    changed = true;
    return hslToHex(next);
  });
  if (kind === 'bg') {
    out = out.replace(/rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*([\d.]+)\s*\)/g, (m, a) => {
      if (Number(a) < 0.5) return m;
      changed = true;
      return `rgba(24,24,32,${a})`;
    });
  }
  return changed ? out : null;
}

// ── walk each stylesheet ──────────────────────────────────────────────────────
const SKIP_SEL = /^(html|body|:root)\b/;
let css = '/* AUTO-GENERATED by scripts/gen-dark-theme.mjs. Do not edit by hand. */\n';

for (const file of SOURCES) {
  const ast = postcss.parse(readFileSync(resolve(root, file), 'utf8'));
  css += `\n/* ${file.replace(/^src\//, '')} */\n`;
  const emit = (rule, indent = '') => {
    if (rule.parent?.type === 'atrule' && /keyframes/.test(rule.parent.name)) return '';
    const decls = [];
    rule.walkDecls((d) => {
      if (d.parent !== rule) return;
      const next = transform(d.prop, d.value);
      if (next) decls.push(`${d.prop}:${next}${d.important ? '!important' : ''}`);
    });
    if (!decls.length) return '';
    const sels = rule.selectors.filter((s) => !SKIP_SEL.test(s.trim())).map((s) => `html[data-theme='dark'] ${s.trim()}`);
    return sels.length ? `${indent}${sels.join(',\n' + indent)} { ${decls.join('; ')}; }\n` : '';
  };
  ast.each((node) => {
    if (node.type === 'rule') css += emit(node);
    else if (node.type === 'atrule' && /^(media|supports)$/.test(node.name)) {
      let inner = '';
      node.each((n) => { if (n.type === 'rule') inner += emit(n, '  '); });
      if (inner) css += `@${node.name} ${node.params} {\n${inner}}\n`;
    }
  });
}

writeFileSync(resolve(root, 'src/styles/dark-dashboards.css'), css);
console.log('wrote src/styles/dark-dashboards.css', css.split('\n').length, 'lines');
